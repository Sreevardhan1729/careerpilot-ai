#!/usr/bin/env node
// Regenerates the API contract artifacts from the FastAPI app:
//   1. backend → openapi.json        (uv run python -I scripts/export_openapi.py)
//   2. openapi.json → types/api.d.ts (openapi-typescript)
//   3. openapi.json → lib/api-capabilities.generated.ts (which METHOD + path pairs exist)
//
// Set SKIP_EXPORT=1 to reuse the existing openapi.json (e.g. when the backend toolchain is unavailable).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backend = resolve(root, "../backend");
const openapiPath = resolve(root, "openapi.json");

if (!process.env.SKIP_EXPORT) {
  execFileSync("uv", ["run", "python", "-I", "scripts/export_openapi.py", openapiPath], {
    cwd: backend,
    stdio: "inherit",
  });
}

execFileSync(
  process.execPath,
  [resolve(root, "node_modules/openapi-typescript/bin/cli.js"), openapiPath, "-o", resolve(root, "types/api.d.ts")],
  { cwd: root, stdio: "inherit" },
);

const spec = JSON.parse(readFileSync(openapiPath, "utf8"));
const PREFIX = "/api/v1";
const ops = [];
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of Object.keys(item)) {
    if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
    const rel = path.startsWith(PREFIX) ? path.slice(PREFIX.length) || "/" : path;
    // Normalise path parameter names so callers don't depend on the backend's naming.
    ops.push(`${method.toUpperCase()} ${rel.replace(/\{[^}]+\}/g, "{}")}`);
  }
}
ops.sort();

const out = `// GENERATED by scripts/gen-api.mjs from openapi.json — do not edit by hand.
// The set of operations the backend exposes. The UI only renders actions whose endpoint is listed here.
export const API_OPERATIONS: readonly string[] = ${JSON.stringify(ops, null, 2)};
`;
writeFileSync(resolve(root, "lib/api-capabilities.generated.ts"), out);
console.log(`wrote types/api.d.ts and lib/api-capabilities.generated.ts (${ops.length} operations)`);
